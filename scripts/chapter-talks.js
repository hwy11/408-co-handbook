window.renderChapterTalk = function renderChapterTalk(chapter) {
  const talk = window.CHAPTER_TALKS && window.CHAPTER_TALKS[chapter];
  if (!talk) return `<div class="card">本章串讲内容加载中...</div>`;
  return `
    <section class="talk-hero">
      <div class="talk-eyebrow">${talk.eyebrow}</div>
      <h1>${talk.title}</h1>
      <p>${talk.lead}</p>
    </section>
    <section class="talk-map">
      ${talk.map.map((item, index) => `<div><span>${String(index + 1).padStart(2, "0")}</span><b>${item}</b></div>`).join("")}
    </section>
    <section class="talk-thread">
      ${talk.body.map((paragraph, index) => `<article><div class="talk-step">${String(index + 1).padStart(2, "0")}</div><p>${paragraph.replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>")}</p></article>`).join("")}
    </section>
    <section class="talk-drills">
      <div class="talk-drill-head">串讲后立刻自测</div>
      ${talk.drills.map(([q, a]) => `<article><h3>${q}</h3><p>${a}</p></article>`).join("")}
    </section>
  `;
};
